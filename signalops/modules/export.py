"""
SignalOps — rapor dışa aktarma: CSV, GeoJSON, KML, PDF.

Uç noktalar
  POST /api/export/<fmt>                 body {devices:[…], meta:{title,kind,lat,lon,label}}  → anlık sonuç
  GET  /api/scans/<id>/export/<fmt>      kayıtlı tarama
  GET  /api/cases/<id>/export/<fmt>      vaka raporu (tüm taramalar + notlar + işaretli cihazlar)
fmt: csv | geojson | kml | pdf
"""
import io, csv, json, time, os
from datetime import datetime, timezone
from xml.sax.saxutils import escape as xesc
from flask import Blueprint, request, jsonify, Response

from . import store

bp = Blueprint("export", __name__)
FORMATS = {
    "csv":     ("text/csv; charset=utf-8", "csv"),
    "geojson": ("application/geo+json", "geojson"),
    "kml":     ("application/vnd.google-earth.kml+xml", "kml"),
    "pdf":     ("application/pdf", "pdf"),
}
MAX_EXPORT = 20000
FONT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")

CSV_COLS = ["name", "type", "source", "risk", "lat", "lon", "loc_quality", "ip", "ip_addr", "port",
            "bssid", "ssid", "encryption", "vendor", "org", "operator", "country", "city",
            "mcc", "mnc", "lac", "cell_id", "radio", "icao", "callsign", "altitude", "squawk",
            "mmsi", "ship_name", "banner", "timestamp", "scan_label"]

def _name(d):
    return store.device_name(d)

def _ident(d):
    return str(d.get("ip_addr") or d.get("ip") or d.get("bssid") or d.get("cell_id")
               or d.get("icao") or d.get("mmsi") or "")

def _safe_cell(v):
    """CSV/Excel formül enjeksiyonuna karşı (=,+,-,@ ile başlayan metinler)."""
    if v is None:
        return ""
    if isinstance(v, (list, dict)):
        v = json.dumps(v, ensure_ascii=False)
    s = str(v)
    if s and s[0] in "=+-@\t\r" and not _is_number(s):
        s = "'" + s
    return s

def _is_number(s):
    try: float(s); return True
    except ValueError: return False

def _num(v):
    try:
        x = float(v)
        return x if x == x else None
    except (TypeError, ValueError):
        return None

def _clean(devices):
    return [d for d in (devices or []) if isinstance(d, dict)][:MAX_EXPORT]

# ── Biçimler ─────────────────────────────────────────────
def build_csv(devices):
    buf = io.StringIO()
    buf.write("﻿")   # Excel'de Türkçe karakterler doğru açılsın
    w = csv.writer(buf)
    w.writerow(CSV_COLS)
    for d in devices:
        w.writerow([_safe_cell(_name(d) if c == "name" else d.get(c)) for c in CSV_COLS])
    return buf.getvalue().encode("utf-8")

def build_geojson(devices, meta=None):
    feats = []
    for d in devices:
        lat, lon = _num(d.get("lat")), _num(d.get("lon"))
        if lat is None or lon is None:
            continue
        props = {k: v for k, v in d.items() if k not in ("lat", "lon") and not isinstance(v, (dict, list))}
        props["name"] = _name(d)
        feats.append({"type": "Feature", "geometry": {"type": "Point", "coordinates": [lon, lat]}, "properties": props})
    fc = {"type": "FeatureCollection", "features": feats,
          "metadata": dict(meta or {}, generated=datetime.now(timezone.utc).isoformat(), generator="SignalOps")}
    return json.dumps(fc, ensure_ascii=False, default=str).encode("utf-8")

_KML_STYLES = {"crit": "ff4444f8", "high": "ff24bffb", "low": "ff80de4a", "approx": "8824bffb"}  # aabbggrr

def build_kml(devices, meta=None):
    meta = meta or {}
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<kml xmlns="http://www.opengis.net/kml/2.2"><Document>',
           f"<name>{xesc(str(meta.get('title') or 'SignalOps export'))}</name>",
           f"<description>{xesc('Generated by SignalOps · ' + datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC'))}</description>"]
    for sid, color in _KML_STYLES.items():
        out.append(f'<Style id="{sid}"><IconStyle><color>{color}</color><scale>1.0</scale>'
                   '<Icon><href>http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png</href></Icon>'
                   '</IconStyle></Style>')
    by_type = {}
    for d in devices:
        if _num(d.get("lat")) is None or _num(d.get("lon")) is None:
            continue
        by_type.setdefault(str(d.get("type") or "unknown"), []).append(d)
    for t, items in sorted(by_type.items()):
        out.append(f"<Folder><name>{xesc(t)} ({len(items)})</name>")
        for d in items:
            risk = int(_num(d.get("risk")) or 0)
            style = "approx" if d.get("approx") else "crit" if risk >= 70 else "high" if risk >= 40 else "low"
            desc_rows = [(k, d.get(k)) for k in ("type", "source", "risk", "ip_addr", "ip", "port", "bssid", "encryption",
                                                  "vendor", "org", "operator", "country", "icao", "mmsi", "banner")
                         if d.get(k) not in (None, "")]
            if d.get("approx"):
                desc_rows.append(("location", "APPROXIMATE (source gave no coordinates)"))
            elif d.get("loc_quality") == "ip":
                desc_rows.append(("location", "IP geolocation (city-level)"))
            desc = "<br/>".join(f"<b>{xesc(str(k))}</b>: {xesc(str(v))}" for k, v in desc_rows)
            out.append(f"<Placemark><name>{xesc(_name(d))}</name><styleUrl>#{style}</styleUrl>"
                       f"<description><![CDATA[{desc.replace(']]>', ']]&gt;')}]]></description>"
                       f"<Point><coordinates>{_num(d['lon'])},{_num(d['lat'])},0</coordinates></Point></Placemark>")
        out.append("</Folder>")
    out.append("</Document></kml>")
    return "\n".join(out).encode("utf-8")

def _pdf_fonts():
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    try:
        pdfmetrics.getFont("SO-Sans")
    except KeyError:
        pdfmetrics.registerFont(TTFont("SO-Sans", os.path.join(FONT_DIR, "DejaVuSans.ttf")))
        pdfmetrics.registerFont(TTFont("SO-Sans-Bold", os.path.join(FONT_DIR, "DejaVuSans-Bold.ttf")))
        from reportlab.pdfbase.pdfmetrics import registerFontFamily
        registerFontFamily("SO-Sans", normal="SO-Sans", bold="SO-Sans-Bold", italic="SO-Sans", boldItalic="SO-Sans-Bold")
    return "SO-Sans", "SO-Sans-Bold"

def build_pdf(devices, meta=None, sections=None, max_rows=600):
    """sections: [(başlık, [satır metinleri])] — notlar, değişiklikler, işaretli cihazlar gibi ek bölümler."""
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib import colors
    from reportlab.lib.units import mm
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    meta = meta or {}
    reg, bold = _pdf_fonts()
    P = lambda size, font=reg, color=colors.HexColor("#1F2937"), lead=None: ParagraphStyle(
        "x", fontName=font, fontSize=size, leading=lead or size * 1.35, textColor=color)
    st_title, st_h, st_b, st_s = P(20, bold, colors.HexColor("#5B21B6")), P(12, bold), P(9), P(7.5)

    def esc(v):
        return xesc(str(v if v is not None else ""))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=14*mm, rightMargin=14*mm,
                            topMargin=14*mm, bottomMargin=14*mm,
                            title=str(meta.get("title") or "SignalOps report"), author="SignalOps")
    story = [Paragraph(esc(meta.get("title") or "SignalOps Report"), st_title), Spacer(1, 4*mm)]

    gen = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    info = [("Generated", gen)]
    for k, label in (("kind", "Scan type"), ("label", "Label"), ("case", "Case"), ("created", "Scan time")):
        if meta.get(k):
            info.append((label, meta[k]))
    if meta.get("lat") is not None and meta.get("lon") is not None:
        info.append(("Center", f"{_num(meta['lat']):.5f}, {_num(meta['lon']):.5f}"))
    info.append(("Devices", str(len(devices))))
    t = Table([[Paragraph(f"<b>{esc(a)}</b>", st_b), Paragraph(esc(b), st_b)] for a, b in info],
              colWidths=[40*mm, 200*mm], hAlign="LEFT")
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#E5E7EB")),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [t, Spacer(1, 5*mm)]

    # Özet
    def counts(key):
        c = {}
        for d in devices:
            v = str(d.get(key) or "unknown"); c[v] = c.get(v, 0) + 1
        return sorted(c.items(), key=lambda x: -x[1])
    risk_b = {"Critical (≥70)": 0, "High (40–69)": 0, "Low (<40)": 0}
    for d in devices:
        r = _num(d.get("risk")) or 0
        risk_b["Critical (≥70)" if r >= 70 else "High (40–69)" if r >= 40 else "Low (<40)"] += 1
    approx = sum(1 for d in devices if d.get("approx"))
    cols = [("By type", counts("type")[:12]), ("By source", counts("source")[:12]), ("By risk", list(risk_b.items()))]
    cells = []
    for title, items in cols:
        txt = f"<b>{esc(title)}</b><br/>" + "<br/>".join(f"{esc(k)}: {v}" for k, v in items)
        cells.append(Paragraph(txt, st_b))
    st = Table([cells], colWidths=[85*mm, 85*mm, 85*mm], hAlign="LEFT")
    st.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                            ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#D1D5DB")),
                            ("INNERGRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D1D5DB")),
                            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9FAFB"))]))
    story += [Paragraph("Summary", st_h), Spacer(1, 2*mm), st]
    if approx:
        story += [Spacer(1, 2*mm), Paragraph(f"{approx} device(s) have APPROXIMATE positions (source gave no coordinates).", st_s)]
    story.append(Spacer(1, 5*mm))

    for title, lines in (sections or []):
        if not lines:
            continue
        story += [Paragraph(esc(title), st_h), Spacer(1, 1.5*mm)]
        for ln in lines[:400]:
            story.append(Paragraph("• " + esc(ln), st_b))
        story.append(Spacer(1, 4*mm))

    # Cihaz tablosu
    rows_ = sorted(devices, key=lambda d: -(_num(d.get("risk")) or 0))[:max_rows]
    if rows_:
        story += [Spacer(1, 4*mm), Paragraph(f"Devices ({len(rows_)}{' of ' + str(len(devices)) if len(devices) > len(rows_) else ''}, by risk)", st_h), Spacer(1, 2*mm)]
        head = ["#", "Name", "Type", "Source", "Identifier", "Risk", "Lat, Lon", "Details"]
        data = [[Paragraph(f"<b>{h}</b>", st_s) for h in head]]
        for i, d in enumerate(rows_, 1):
            lat, lon = _num(d.get("lat")), _num(d.get("lon"))
            loc = f"{lat:.5f}, {lon:.5f}" + (" ≈" if d.get("approx") else "") if lat is not None and lon is not None else "—"
            det = " · ".join(str(x) for x in (d.get("encryption"), d.get("vendor") or d.get("org") or d.get("operator"),
                                               d.get("country")) if x)
            data.append([Paragraph(str(i), st_s), Paragraph(esc(_name(d))[:120], st_s), Paragraph(esc(d.get("type")), st_s),
                         Paragraph(esc(d.get("source")), st_s), Paragraph(esc(_ident(d))[:60], st_s),
                         Paragraph(str(int(_num(d.get("risk")) or 0)), st_s), Paragraph(esc(loc), st_s),
                         Paragraph(esc(det)[:160], st_s)])
        tbl = Table(data, colWidths=[9*mm, 55*mm, 22*mm, 24*mm, 42*mm, 12*mm, 34*mm, 70*mm], repeatRows=1)
        style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDE9FE")),
                 ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#E5E7EB")),
                 ("VALIGN", (0, 0), (-1, -1), "TOP")]
        for i, d in enumerate(rows_, 1):
            r = _num(d.get("risk")) or 0
            if r >= 70: style.append(("BACKGROUND", (5, i), (5, i), colors.HexColor("#FEE2E2")))
            elif r >= 40: style.append(("BACKGROUND", (5, i), (5, i), colors.HexColor("#FEF3C7")))
        tbl.setStyle(TableStyle(style))
        story.append(tbl)

    def footer(canvas, _doc):
        canvas.saveState()
        canvas.setFont(reg, 7)
        canvas.setFillColor(colors.HexColor("#6B7280"))
        canvas.drawString(14*mm, 8*mm, f"SignalOps · {gen}")
        canvas.drawRightString(landscape(A4)[0] - 14*mm, 8*mm, f"Page {_doc.page}")
        canvas.restoreState()
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()

def render(fmt, devices, meta=None, sections=None):
    devices = _clean(devices)
    if fmt == "csv":     return build_csv(devices)
    if fmt == "geojson": return build_geojson(devices, meta)
    if fmt == "kml":     return build_kml(devices, meta)
    if fmt == "pdf":     return build_pdf(devices, meta, sections)
    raise ValueError(fmt)

def _file_response(fmt, payload, base):
    mime, ext = FORMATS[fmt]
    from urllib.parse import quote
    import unicodedata
    stamp = time.strftime('%Y%m%d_%H%M%S')
    # ASCII yedek ad (Kadıköy → Kadikoy) + RFC 5987 UTF-8 adı — Türkçe karakterler header'ı bozmasın
    tr = str(base).translate(str.maketrans("ıİşŞğĞüÜöÖçÇ", "iIsSgGuUoOcC"))
    ascii_base = unicodedata.normalize("NFKD", tr).encode("ascii", "ignore").decode()
    safe = "".join(c if (c.isascii() and c.isalnum()) or c in "-_" else "_" for c in ascii_base)[:60].strip("_") or "signalops"
    utf8 = "".join(c if c.isalnum() or c in "-_" else "_" for c in str(base))[:60].strip("_") or "signalops"
    fname = f"{safe}_{stamp}.{ext}"
    disp = f"attachment; filename=\"{fname}\"; filename*=UTF-8''{quote(f'{utf8}_{stamp}.{ext}')}"
    return Response(payload, mimetype=mime.split(";")[0],
                    headers={"Content-Disposition": disp,
                             "Content-Type": mime, "Cache-Control": "no-store"})

def _bad_fmt(fmt):
    return jsonify({"error": f"Unknown format '{fmt}'. Use: {', '.join(FORMATS)}"}), 400

# ── Uç noktalar ──────────────────────────────────────────
@bp.route("/api/export/<fmt>", methods=["POST"])
def export_live(fmt):
    if fmt not in FORMATS:
        return _bad_fmt(fmt)
    body = request.get_json(silent=True)
    if not isinstance(body, dict) or not isinstance(body.get("devices"), list):
        return jsonify({"error": "JSON body {devices:[…], meta:{…}} required"}), 400
    meta = body.get("meta") if isinstance(body.get("meta"), dict) else {}
    meta = {k: str(v)[:200] if not isinstance(v, (int, float)) else v for k, v in meta.items()}
    try:
        payload = render(fmt, body["devices"], meta)
    except Exception as e:
        print(f"[export/{fmt}] {e}")
        return jsonify({"error": "Export failed — see server log"}), 500
    return _file_response(fmt, payload, meta.get("title") or meta.get("kind") or "signalops")

@bp.route("/api/scans/<int:scan_id>/export/<fmt>")
def export_scan(scan_id, fmt):
    if fmt not in FORMATS:
        return _bad_fmt(fmt)
    s = store.get_scan(scan_id)
    if not s:
        return jsonify({"error": "scan not found"}), 404
    meta = {"title": s.get("label") or f"Scan #{scan_id}", "kind": s["kind"], "label": s.get("label"),
            "lat": s.get("lat"), "lon": s.get("lon"),
            "created": datetime.fromtimestamp(s["created_at"], timezone.utc).strftime("%Y-%m-%d %H:%M UTC")}
    sections = []
    if fmt == "pdf":
        dif = store.diff_scans(scan_id)
        if dif.get("old_scan"):
            sections.append((f"Changes vs. previous scan #{dif['old_scan']}",
                             [f"NEW: {x['name']} ({x['type']}, {x['source']})" for x in dif["new"][:100]] +
                             [f"GONE: {x['name']} ({x['type']}, {x['source']})" for x in dif["gone"][:100]] +
                             [f"CHANGED: {x['name']} — {', '.join(x['changes'])}" for x in dif["changed"][:100]]))
    for d in s["devices"]:
        d.pop("_key", None)
    return _file_response(fmt, render(fmt, s["devices"], meta, sections), meta["title"])

@bp.route("/api/cases/<int:case_id>/export/<fmt>")
def export_case(case_id, fmt):
    if fmt not in FORMATS:
        return _bad_fmt(fmt)
    with store.db() as c:
        case = store.row(c.execute("SELECT * FROM cases WHERE id=?", (case_id,)).fetchone())
        if not case:
            return jsonify({"error": "case not found"}), 404
        scans = store.rows(c.execute("SELECT * FROM scans WHERE case_id=? ORDER BY created_at", (case_id,)))
        notes = store.rows(c.execute("SELECT * FROM notes WHERE case_id=? ORDER BY created_at", (case_id,)))
        flags = store.rows(c.execute("SELECT * FROM flags WHERE case_id=? ORDER BY created_at", (case_id,)))
        devs, seen = [], set()
        for s in reversed(scans):   # en yeni görünüm öncelikli
            for r in c.execute("SELECT dev_key, data FROM scan_devices WHERE scan_id=?", (s["id"],)):
                if r["dev_key"] in seen:
                    continue
                seen.add(r["dev_key"])
                d = json.loads(r["data"]); d["scan_label"] = s.get("label") or f"#{s['id']} {s['kind']}"
                devs.append(d)
    fmt_t = lambda ts: datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%d %H:%M")
    meta = {"title": f"Case: {case['name']}", "case": case["name"], "label": case.get("description") or ""}
    sections = [
        ("Scans", [f"#{s['id']} · {s['kind']} · {s.get('label') or ''} · {s['device_count']} devices · {fmt_t(s['created_at'])}" for s in scans]),
        ("Flagged devices", [f"{f['dev_key']} — {f.get('label') or ''}" for f in flags]),
        ("Notes", [f"{fmt_t(n['created_at'])} — {n['body']}" for n in notes]),
    ]
    return _file_response(fmt, render(fmt, devs, meta, sections), f"case_{case['name']}")

